"""
Experiment 3: KG vs No-KG Output Quality Ablation

Compares system outputs WITH and WITHOUT knowledge graph personalisation.
Uses LLM-as-judge to score explanation quality on 4 dimensions (1-5 scale).
"""

import json
import os
import sys
import dspy
from tqdm import tqdm

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from experiments.config import (
    configure_teacher_lm, load_knowledge_graph, create_fresh_learner,
    sample_concepts, RESULTS_DIR, setup_logging, timed
)

log = setup_logging("exp3")


class QualityJudgeSignature(dspy.Signature):
    """Judge the pedagogical quality of a learning system output on a 1-5 scale."""
    explanation: str = dspy.InputField(desc="The explanation generated by the learning system")
    concept_name: str = dspy.InputField(desc="The concept being explained")
    mastery_level: str = dspy.InputField(desc="beginner/intermediate/advanced")
    prerequisites: str = dspy.InputField(desc="Known prerequisites for this concept")
    mode: str = dspy.InputField(desc="'with_kg' or 'without_kg'")

    coherence_score: int = dspy.OutputField(desc="1-5: Logical structure and flow")
    prerequisite_awareness: int = dspy.OutputField(desc="1-5: Builds on prerequisite knowledge")
    depth_calibration: int = dspy.OutputField(desc="1-5: Depth matches mastery level")
    overall_quality: int = dspy.OutputField(desc="1-5: Overall pedagogical quality")
    reasoning: str = dspy.OutputField(desc="Brief justification")


def run_kg_ablation():
    log.info("=" * 60)
    log.info("EXPERIMENT 3: KG vs No-KG Quality Ablation")
    log.info("=" * 60)

    with timed(log, "Configuring LM"):
        lm = configure_teacher_lm()
    kg = load_knowledge_graph()

    from backend.agents.source_curator import SourceCuratorAgent
    from backend.agents.learning_curator import LearningCuratorAgent
    from backend.core.knowledge_graph import KnowledgeGraph, ConceptNode

    judge = dspy.ChainOfThought(QualityJudgeSignature)
    concepts = sample_concepts(kg, n=1, strategy="diverse")
    log.info(f"Sampled {len(concepts)} concept(s)")

    results = []

    for cid, concept in concepts:
        prereq_names = [kg.get_concept(p).name for p in concept.prerequisites if kg.get_concept(p)]
        concept_result = {"concept_id": cid, "concept_name": concept.name, "modes": {}}

        for mode in tqdm(["with_kg", "without_kg"], desc=f"{concept.name[:20]}"):
            with timed(log, f"[{mode}] {concept.name}"):
                if mode == "with_kg":
                    source_curator = SourceCuratorAgent(kg)
                    learning_curator = LearningCuratorAgent(kg)
                else:
                    minimal_kg = KnowledgeGraph()
                    minimal_concept = ConceptNode(
                        id=cid, name=concept.name, description=concept.description,
                        difficulty=concept.difficulty, bloom_ceiling=concept.bloom_ceiling,
                        prerequisites=[], related_concepts=[], lecture_source=concept.lecture_source,
                    )
                    minimal_kg.concepts[cid] = minimal_concept
                    source_curator = SourceCuratorAgent(minimal_kg)
                    learning_curator = LearningCuratorAgent(minimal_kg)

                learner = create_fresh_learner(f"kg_{mode}")
                learner.get_concept_state(cid).mastery = 0.3
                learner.enroll_in_course("experiment", [cid])

                try:
                    source_result = source_curator.curate(learner, cid)
                    source_material = source_result.get("curated_document", concept.description)
                    session = learning_curator.create_session(learner, cid, source_material=source_material)
                    explanation = session.get("explanation", "")

                    judgement = judge(
                        explanation=explanation[:3000], concept_name=concept.name,
                        mastery_level="intermediate",
                        prerequisites=", ".join(prereq_names) if prereq_names else "none",
                        mode=mode,
                    )

                    scores = {
                        "coherence": int(judgement.coherence_score),
                        "prerequisite_awareness": int(judgement.prerequisite_awareness),
                        "depth_calibration": int(judgement.depth_calibration),
                        "overall_quality": int(judgement.overall_quality),
                    }
                    concept_result["modes"][mode] = {
                        "scores": scores, "reasoning": judgement.reasoning,
                        "word_count": len(explanation.split()),
                    }
                    log.info(f"  Scores: {scores}")
                except Exception as e:
                    log.error(f"  Error: {e}")
                    concept_result["modes"][mode] = {"error": str(e)}

        results.append(concept_result)

    # Aggregate
    metrics = ["coherence", "prerequisite_awareness", "depth_calibration", "overall_quality"]
    wk = {m: [] for m in metrics}
    nk = {m: [] for m in metrics}
    for r in results:
        for m in metrics:
            if "with_kg" in r["modes"] and "scores" in r["modes"]["with_kg"]:
                wk[m].append(r["modes"]["with_kg"]["scores"][m])
            if "without_kg" in r["modes"] and "scores" in r["modes"]["without_kg"]:
                nk[m].append(r["modes"]["without_kg"]["scores"][m])

    avg = lambda lst: round(sum(lst) / len(lst), 2) if lst else 0
    summary = {
        "with_kg_averages": {m: avg(wk[m]) for m in metrics},
        "without_kg_averages": {m: avg(nk[m]) for m in metrics},
        "delta": {m: round(avg(wk[m]) - avg(nk[m]), 2) for m in metrics},
    }

    report = {"experiment": "kg_ablation_quality", "per_concept_results": results, "summary": summary}

    out_path = os.path.join(RESULTS_DIR, "exp3_kg_ablation.json")
    with open(out_path, "w") as f:
        json.dump(report, f, indent=2)

    log.info("")
    log.info(f"{'Metric':25s} {'With KG':>8s} {'No KG':>8s} {'Delta':>8s}")
    for m in metrics:
        log.info(f"  {m:25s} {summary['with_kg_averages'][m]:8.2f} {summary['without_kg_averages'][m]:8.2f} {summary['delta'][m]:+8.2f}")
    log.info(f"Results → {out_path}")
    return report


if __name__ == "__main__":
    run_kg_ablation()
